class RiskScoringServer:
    """
    Wraps the gRPC server lifecycle.
    Handles startup, graceful shutdown, and signal handling.
    """

    def __init__(self, cfg: ServiceConfig):
        self.cfg      = cfg
        self.servicer = RiskScoringServicer(cfg)
        self.server   = None

    def start(self):
        self.server = grpc.server(
            futures.ThreadPoolExecutor(max_workers=self.cfg.max_workers),
            options=[
                ("grpc.max_receive_message_length", 4 * 1024 * 1024),  # 4MB
                ("grpc.max_send_message_length",    4 * 1024 * 1024),
                ("grpc.keepalive_time_ms",          30_000),
                ("grpc.keepalive_timeout_ms",       10_000),
            ],
        )

        # Register the servicer using generated proto stubs.
        # Stubs are produced by: bash scripts/compile_proto.sh
        if _PROTO_AVAILABLE:
            pb2_grpc.add_RiskScoringServiceServicer_to_server(self.servicer, self.server)
            logger.info("RiskScoringService registered via generated proto stubs.")
        else:
            # Development fallback: server starts but agents cannot connect.
            # Run 'bash scripts/compile_proto.sh' and restart before connecting any agent.
            logger.warning(
                "Proto stubs not found — RiskScoringService NOT registered. "
                "Run compile_proto.sh and restart."
            )

        addr = f"{self.cfg.host}:{self.cfg.port}"
        if self.cfg.tls_enabled:
            server_credentials = self._load_mtls_credentials()
            self.server.add_secure_port(addr, server_credentials)
            logger.info(f"gRPC server listening on {addr} [mTLS enabled]")
        else:
            self.server.add_insecure_port(addr)
            logger.warning(f"gRPC server listening on {addr} [PLAINTEXT — dev only]")
        self.server.start()
        logger.info(f"gRPC server listening on {addr}")

    def _load_mtls_credentials(self):
        """Load server certificate, key, and CA cert for mTLS."""
        with open(self.cfg.tls_cert_file, "rb") as f:
            certificate_chain = f.read()
        with open(self.cfg.tls_key_file, "rb") as f:
            private_key = f.read()
        with open(self.cfg.tls_ca_file, "rb") as f:
            root_certificates = f.read()
        return grpc.ssl_server_credentials(
            [(private_key, certificate_chain)],
            root_certificates=root_certificates,
            require_client_auth=True,  # strict mTLS
        )

    def stop(self, grace: float = 5.0):
        if self.server:
            logger.info("Shutting down gRPC server...")
            self.server.stop(grace)
            logger.info("Server stopped.")

    def wait_for_termination(self):
        self.server.wait_for_termination()

    def run_until_interrupt(self):
        """Start server and block until SIGINT/SIGTERM."""
        self.start()

        def _shutdown(sig, frame):
            logger.info(f"Received signal {sig} — initiating graceful shutdown")
            self.stop()

        signal.signal(signal.SIGINT,  _shutdown)
        signal.signal(signal.SIGTERM, _shutdown)

        logger.info("Server running. Press Ctrl+C to stop.")
        self.wait_for_termination()


