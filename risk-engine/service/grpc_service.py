class RiskScoringServicer(_ServicerBase):
    """
    gRPC servicer implementing the RiskScoringService contract.

    Stateful: maintains active session registry and model state.
    Thread-safe for concurrent agent connections.
    """

    def __init__(self, cfg: ServiceConfig):
        self.cfg         = cfg
        self.started_at  = time.time()

        # Core components
        self.preprocessor = FeaturePreprocessor(cfg.user_stats_dir)
        self.risk_scorer  = RiskScorer()
        self.profile_store = ProfileStore()

        # Session registry
        self._sessions: dict[str, SessionState] = {}

        # Model
        self.model: Optional[SiameseNetwork] = None
        self._load_model()

        # Trainer for fine-tuning
        train_cfg = TrainingConfig(
            checkpoint_dir=cfg.checkpoint_dir,
            finetune_lr=1e-4,
            finetune_epochs=5,
            max_risk_score_for_adapt=cfg.adapt_max_risk,
        )
        self.trainer: Optional[SiameseTrainer] = None
        if self.model:
            self.trainer = SiameseTrainer(self.model, cfg=train_cfg)

        logger.info(f"RiskScoringServicer ready on {cfg.host}:{cfg.port}")

    def _load_model(self):
        path = Path(self.cfg.model_path)
        if path.exists():
            try:
                self.model = load_model(str(path))
                self.model.eval()
                logger.info(f"Model loaded from {path}")
            except Exception as e:
                logger.error(f"Failed to load model: {e}")
                self._init_fresh_model()
        else:
            logger.warning(f"No model found at {path} — initializing fresh model")
            self._init_fresh_model()

    def _init_fresh_model(self):
        self.model = build_model(SiameseConfig())
        self.model.eval()
        logger.info("Fresh model initialized (untrained)")

    # ── Session management ────────────────────────────────

    def _get_or_create_session(self, fv: FeatureVector) -> SessionState:
        if fv.session_id not in self._sessions:
            # Evict stale sessions if at capacity
            if len(self._sessions) >= self.cfg.max_active_sessions:
                self._evict_stale_sessions()

            self._sessions[fv.session_id] = SessionState(
                user_id=fv.user_id,
                session_id=fv.session_id,
                device_id=fv.device_id,
            )
            logger.info(f"New session: {fv.session_id} (user={fv.user_id})")

        return self._sessions[fv.session_id]

    def _evict_stale_sessions(self):
        stale = [sid for sid, s in self._sessions.items() if s.is_stale]
        for sid in stale:
            del self._sessions[sid]
        if stale:
            logger.info(f"Evicted {len(stale)} stale sessions")

    # ── Core scoring logic ────────────────────────────────

    def _score_feature_vector(
        self,
        fv: FeatureVector,
        session: SessionState,
    ) -> RiskScoreResponse:
        """Process one feature vector and return a risk score response."""

        # 1. Build RawFeatures from proto message
        if len(fv.features) != FEATURE_DIM:
            logger.warning(
                f"Expected {FEATURE_DIM} features, got {len(fv.features)} "
                f"for session {fv.session_id} — padding with zeros"
            )
            features = list(fv.features) + [0.0] * (FEATURE_DIM - len(fv.features))
            features = features[:FEATURE_DIM]
        else:
            features = list(fv.features)

        raw = RawFeatures.from_dict({
            name: features[idx]
            for name, idx in __import__('preprocessor').FEATURE_INDEX.items()
        })
        raw.user_id    = fv.user_id
        raw.device_id  = fv.device_id
        raw.session_id = fv.session_id
        raw.timestamp  = float(fv.timestamp)

        # 2. Preprocess
        result    = self.preprocessor.process(raw)
        norm_vec  = result["normalized_vector"]
        sequence  = result["sequence"]
        phase     = self.preprocessor.get_user_phase(fv.user_id)

        # 3. If sequence is ready, run Siamese inference
        behavioral_deviation = 25.0   # Default mid-point when no sequence yet
        similarity_score     = 0.5
        classification       = "UNKNOWN"
        confidence           = 0.5

        if result["sequence_ready"] and sequence is not None:
            session.record_sequence(sequence)

            anchor_seq = self.profile_store.get(fv.user_id)

            if anchor_seq is None:
                # First time we have a full sequence — use it as the anchor profile
                self.profile_store.set(fv.user_id, sequence)
                anchor_seq = sequence
                logger.info(f"Initial profile set for user '{fv.user_id}'")

            # Run model inference
            anchor_t = torch.tensor(anchor_seq[np.newaxis], dtype=torch.float32)
            sample_t = torch.tensor(sequence[np.newaxis],   dtype=torch.float32)

            prediction = self.model.predict_risk(anchor_t, sample_t)
            behavioral_deviation = prediction["behavioral_deviation"]
            similarity_score     = prediction["similarity_score"]
            classification       = prediction["classification"]
            confidence           = prediction["confidence"]

        # 4. Compute full risk score
        scores = self.risk_scorer.compute(
            behavioral_deviation=behavioral_deviation,
            normalized_vector=norm_vec,
            phase=phase,
            soft_multiplier=self.cfg.soft_phase_multiplier,
        )

        # 5. Record score in session state
        session.record_score(scores["risk_score"])

        logger.debug(
            f"[{fv.session_id}] score={scores['risk_score']:.1f}  "
            f"behav={scores['behavioral_deviation']:.1f}  "
            f"ctx={scores['context_deviation']:.1f}  "
            f"dev={scores['device_risk']:.1f}  "
            f"phase={phase}  clf={classification}"
        )

        return RiskScoreResponse(
            user_id=fv.user_id,
            session_id=fv.session_id,
            risk_score=scores["risk_score"],
            behavioral_deviation=scores["behavioral_deviation"],
            similarity_score=similarity_score,
            classification=classification,
            confidence=confidence,
            phase=phase,
            sequence_ready=result["sequence_ready"],
            timestamp=int(time.time()),
        )

    # ── gRPC handlers ─────────────────────────────────────

    def ScoreOnce(self, request: FeatureVector, context=None) -> RiskScoreResponse:
        """
        Unary RPC — score a single feature vector.
        Used for one-off checks or low-frequency polling.
        """
        session = self._get_or_create_session(request)
        return self._score_feature_vector(request, session)

    def ScoreStream(self, request_iterator, context=None):
        """
        Bidirectional streaming RPC — score a continuous stream of vectors.
        Yields one RiskScoreResponse per incoming FeatureVector.
        This is the primary inference path during live sessions.
        """
        session = None
        for fv in request_iterator:
            session = self._get_or_create_session(fv)
            yield self._score_feature_vector(fv, session)

    def EndSession(self, request: SessionEndRequest, context=None) -> AdaptationResponse:
        """
        Unary RPC — called when a session ends cleanly.
        Triggers fine-tuning if conditions are met.
        """
        sid = request.session_id
        uid = request.user_id

        session = self._sessions.get(sid)
        if not session:
            logger.warning(f"EndSession called for unknown session: {sid}")
            return AdaptationResponse(adapted=False, reason="session_not_found")

        # Notify preprocessor
        self.preprocessor.on_session_end(uid, sid)

        # Attempt fine-tuning
        adapted = False
        reason  = "skipped"

        if request.was_flagged:
            reason = "session_was_flagged"
        elif request.avg_risk_score > self.cfg.adapt_max_risk:
            reason = f"avg_risk_too_high ({request.avg_risk_score:.1f})"
        elif len(session.sequences) < self.cfg.min_sequences_for_adapt:
            reason = f"insufficient_sequences ({len(session.sequences)})"
        elif self.trainer is not None:
            adapted = self.trainer.fine_tune(
                user_id=uid,
                session_sequences=session.sequences,
                label="legitimate",
                session_risk_score=session.avg_risk_score,
            )
            reason = "adapted" if adapted else "fine_tune_blocked"

            # Update anchor profile with the last full sequence
            if adapted and session.sequences:
                self.profile_store.set(uid, session.sequences[-1])
                logger.info(f"Profile updated for user '{uid}'")

        # Clean up session
        del self._sessions[sid]
        logger.info(f"Session ended: {sid} — adapted={adapted}, reason={reason}")

        return AdaptationResponse(adapted=adapted, reason=reason)

    def HealthCheck(self, request: HealthRequest, context=None) -> HealthResponse:
        """Liveness/readiness probe for load balancers and monitoring."""
        return HealthResponse(
            healthy=True,
            model_loaded=(self.model is not None),
            active_sessions=len(self._sessions),
            uptime_s=round(time.time() - self.started_at, 1),
        )


