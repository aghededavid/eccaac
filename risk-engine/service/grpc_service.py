def _make_attack_vector(user_id, session_id):
    """Helper: generate an anomalous FeatureVector (simulated attack)."""
    features = np.array([
        800.0, 200.0, 1500.0, 400.0, 0.2, 0.5,    # Typing: very abnormal
        50.0, 10.0, 5.0, 0.1, 0.9,                  # Mouse: very slow
        0.95, 0.98, 0.1,                             # Device: overloaded, new device
        400.0, 1.0, 0.0,                             # Process: many procs, suspicious
        1.0, 5000.0, 50000.0, 1.0,                  # Network: IP changed, far away
        30.0, 0.8, 0.1,                              # Session: short, idle
    ], dtype=np.float32).tolist()
    return FeatureVector(
        user_id=user_id,
        device_id="unknown_device",
        session_id=session_id,
        features=features,
        timestamp=int(time.time()),
    )


