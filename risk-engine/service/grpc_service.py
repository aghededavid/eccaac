@dataclass
class SessionState:
    """Tracks in-flight state for one active user session."""
    user_id:      str
    session_id:   str
    device_id:    str
    started_at:   float = field(default_factory=time.time)
    last_seen_at: float = field(default_factory=time.time)
    vector_count: int   = 0
    risk_scores:  list  = field(default_factory=list)
    sequences:    list  = field(default_factory=list)   # for fine-tuning

    @property
    def avg_risk_score(self) -> float:
        if not self.risk_scores:
            return 0.0
        return float(np.mean(self.risk_scores))

    @property
    def is_stale(self) -> bool:
        return (time.time() - self.last_seen_at) > 3600

    def record_score(self, score: float):
        self.risk_scores.append(score)
        self.last_seen_at = time.time()
        self.vector_count += 1

    def record_sequence(self, seq: np.ndarray):
        self.sequences.append(seq)


# ─────────────────────────────────────────────
#  RISK SCORER
# ─────────────────────────────────────────────

class RiskScorer:
    """
    Computes the final risk score from all signal components.

    Risk Score = Behavioral Deviation + Context Deviation + Device Risk

    Behavioral deviation comes from the Siamese network (max 50).
    Context and device deviations come from the raw feature vector (max 30 + 20).
    """

    # Context signal indices and weights (sum capped at 30)
    CONTEXT_SIGNALS = {
        "ip_change_flag":  (17, 25.0),
        "geo_distance":    (18, 20.0),   # normalized: >0 means far from home
        "vpn_flag":        (20, 10.0),
    }

    # Device signal indices and weights (sum capped at 20)
    DEVICE_SIGNALS = {
        "suspicious_flag": (15, 15.0),
        "device_hash_embed": (13, 20.0), # low embed = unrecognized device
    }

    def compute(
        self,
        behavioral_deviation: float,
        normalized_vector:    np.ndarray,
        phase:                str,
        soft_multiplier:      float = 2.0,
    ) -> dict:
        """
        Args:
            behavioral_deviation: 0–50 from Siamese network
            normalized_vector:    24-dim normalized feature vector
            phase:                OBSERVATION | SOFT | FULL
            soft_multiplier:      Threshold relaxation factor during SOFT phase

        Returns:
            dict with risk_score, context_deviation, device_risk, phase_adjusted_score
        """
        # ── Context deviation (max 30) ──
        context_score = 0.0
        if normalized_vector[17] > 0.5:    # ip_change_flag
            context_score += 25.0
        if normalized_vector[18] > 1.0:    # geo_distance anomaly (>1σ above mean)
            context_score += min(normalized_vector[18] * 5.0, 20.0)
        if normalized_vector[20] > 0.5:    # vpn_flag
            context_score += 10.0
        context_score = min(context_score, 30.0)

        # ── Device risk (max 20) ──
        device_score = 0.0
        if normalized_vector[15] > 0.5:    # suspicious_flag
            device_score += 15.0
        if normalized_vector[13] < -1.5:   # device_hash far below user mean = new device
            device_score += 20.0
        device_score = min(device_score, 20.0)

        # ── Raw risk score ──
        raw_score = behavioral_deviation + context_score + device_score
        raw_score = min(raw_score, 100.0)

        # ── Phase adjustment ──
        if phase == "OBSERVATION":
            phase_adjusted = 0.0   # No enforcement during observation
        elif phase == "SOFT":
            phase_adjusted = raw_score / soft_multiplier
        else:
            phase_adjusted = raw_score

        return {
            "risk_score":           round(phase_adjusted, 2),
            "raw_risk_score":       round(raw_score, 2),
            "behavioral_deviation": round(behavioral_deviation, 2),
            "context_deviation":    round(context_score, 2),
            "device_risk":          round(device_score, 2),
        }


# ─────────────────────────────────────────────
#  PROFILE STORE  (per-user anchor sequences)
# ─────────────────────────────────────────────

class ProfileStore:
    """
    Stores the latest anchor sequence (stored profile) for each user.
    The anchor is the reference input to the Siamese network's first branch.

    In production this would be backed by PostgreSQL + filesystem.
    Here we use an in-memory dict with optional file persistence.
    """

    def __init__(self, storage_dir: str = "./profiles"):
        self.storage_dir = Path(storage_dir)
        self.storage_dir.mkdir(parents=True, exist_ok=True)
        self._profiles: dict[str, np.ndarray] = {}

    def get(self, user_id: str) -> Optional[np.ndarray]:
        if user_id in self._profiles:
            return self._profiles[user_id]
        path = self.storage_dir / f"{user_id}.npy"
        if path.exists():
            profile = np.load(str(path))
            self._profiles[user_id] = profile
            return profile
        return None

    def set(self, user_id: str, sequence: np.ndarray):
        self._profiles[user_id] = sequence.copy()
        np.save(str(self.storage_dir / f"{user_id}.npy"), sequence)

    def has(self, user_id: str) -> bool:
        return user_id in self._profiles or (self.storage_dir / f"{user_id}.npy").exists()


