func protoToRiskEvent(p *riskpb.RiskEvent) types.RiskEvent {
	return types.RiskEvent{
		UserID:              p.UserId,
		DeviceID:            p.DeviceId,
		SessionID:           p.SessionId,
		RiskScore:           float64(p.RiskScore),
		RawRiskScore:        float64(p.RawRiskScore),
		BehavioralDeviation: float64(p.BehavioralDeviation),
		ContextDeviation:    float64(p.ContextDeviation),
		DeviceRisk:          float64(p.DeviceRisk),
		SimilarityScore:     float64(p.SimilarityScore),
		Classification:      p.Classification,
		Confidence:          float64(p.Confidence),
		Phase:               p.Phase,
		SequenceReady:       p.SequenceReady,
		Timestamp:           time.Unix(p.Timestamp, 0),
		EvalTimeMS:          float64(p.EvalTimeMs),
	}
}

func decisionToProto(d types.Decision) *riskpb.PolicyDecision {
	return &riskpb.PolicyDecision{
		SessionId: d.SessionID,
		UserId:    d.UserID,
		RiskScore: float32(d.RiskScore),
		RiskLevel: d.RiskLevel,
		Actions:   d.Actions,
		PolicyId:  d.PolicyID,
		Reason:    d.Reason,
		Escalated: d.Escalated,
		Timestamp: d.Timestamp.Unix(),
	}
}

