// Server wraps the gRPC server and handles lifecycle.
type Server struct {
	cfg      *config.Config
	log      *zap.Logger
	grpcSrv  *grpc.Server
	servicer *PDEServicer
}

// NewServer creates and configures the gRPC server.
// Returns an error if mTLS credentials cannot be loaded.
func NewServer(cfg *config.Config, servicer *PDEServicer, log *zap.Logger) (*Server, error) {
	opts := []grpc.ServerOption{
		grpc.KeepaliveParams(keepalive.ServerParameters{
			MaxConnectionIdle: 5 * time.Minute,
			Time:              30 * time.Second,
			Timeout:           10 * time.Second,
		}),
		grpc.KeepaliveEnforcementPolicy(keepalive.EnforcementPolicy{
			MinTime:             10 * time.Second,
			PermitWithoutStream: true,
		}),
		grpc.UnaryInterceptor(unaryLogger(log)),
		grpc.StreamInterceptor(streamLogger(log)),
	}

	tlsOpt, err := tlsutil.ServerOption(cfg)
	if err != nil {
		return nil, fmt.Errorf("mTLS server credentials: %w", err)
	}
	if tlsOpt != nil {
		opts = append(opts, tlsOpt)
		log.Info("mTLS enabled — agents must present a valid client certificate")
	} else {
		log.Warn("TLS disabled — plaintext gRPC (development only)")
	}

	grpcSrv := grpc.NewServer(opts...)
	riskpb.RegisterPolicyDecisionServiceServer(grpcSrv, servicer)

	return &Server{cfg: cfg, log: log, grpcSrv: grpcSrv, servicer: servicer}, nil
}

// RunUntilInterrupt starts the gRPC server and blocks until SIGINT/SIGTERM.
func (s *Server) RunUntilInterrupt() error {
	lis, err := net.Listen("tcp", s.cfg.Server.GRPCAddr)
	if err != nil {
		return fmt.Errorf("listen %s: %w", s.cfg.Server.GRPCAddr, err)
	}

	s.log.Info("PDE gRPC server listening", zap.String("addr", s.cfg.Server.GRPCAddr))

	errCh := make(chan error, 1)
	go func() { errCh <- s.grpcSrv.Serve(lis) }()

	sigCh := make(chan os.Signal, 1)
	signal.Notify(sigCh, syscall.SIGINT, syscall.SIGTERM)

	select {
	case sig := <-sigCh:
		s.log.Info("Shutdown signal received", zap.String("signal", sig.String()))
		s.grpcSrv.GracefulStop()
		return nil
	case err := <-errCh:
		return err
	}
}

