// PDEServicer implements riskpb.PolicyDecisionServiceServer.
type PDEServicer struct {
	riskpb.UnimplementedPolicyDecisionServiceServer

	cfg      *config.Config
	engine   *policy.Engine
	registry *session.Registry
	db       *store.Store
	log      *zap.Logger
}

// NewPDEServicer creates the gRPC servicer.
func NewPDEServicer(
	cfg *config.Config,
	engine *policy.Engine,
	registry *session.Registry,
	db *store.Store,
	log *zap.Logger,
) *PDEServicer {
	return &PDEServicer{
		cfg:      cfg,
		engine:   engine,
		registry: registry,
		db:       db,
		log:      log,
	}
}

// ─────────────────────────────────────────────
//  EvaluateOnce — unary RPC
// ─────────────────────────────────────────────

func (s *PDEServicer) EvaluateOnce(
	ctx context.Context,
	req *riskpb.RiskEvent,
) (*riskpb.PolicyDecision, error) {

	if req == nil {
		return nil, status.Error(codes.InvalidArgument, "request is nil")
	}

	evt := protoToRiskEvent(req)
	s.registry.Upsert(evt)
	decision := s.engine.Evaluate(evt)
	s.db.RecordDecision(evt, decision)

	s.log.Debug("EvaluateOnce",
		zap.String("session", evt.SessionID),
		zap.Float64("score", evt.RiskScore),
		zap.String("level", decision.RiskLevel),
	)

	return decisionToProto(decision), nil
}

// ─────────────────────────────────────────────
//  EvaluateStream — bidirectional streaming
// ─────────────────────────────────────────────

func (s *PDEServicer) EvaluateStream(
	stream riskpb.PolicyDecisionService_EvaluateStreamServer,
) error {

	s.log.Debug("EvaluateStream opened")
	defer s.log.Debug("EvaluateStream closed")

	for {
		req, err := stream.Recv()
		if err == io.EOF {
			return nil
		}
		if err != nil {
			return status.Errorf(codes.Internal, "stream recv: %v", err)
		}

		evt := protoToRiskEvent(req)
		s.registry.Upsert(evt)
		decision := s.engine.Evaluate(evt)
		s.db.RecordDecision(evt, decision)

		if err := stream.Send(decisionToProto(decision)); err != nil {
			return status.Errorf(codes.Internal, "stream send: %v", err)
		}
	}
}

// ─────────────────────────────────────────────
//  EndSession
// ─────────────────────────────────────────────

func (s *PDEServicer) EndSession(
	ctx context.Context,
	req *riskpb.PDESessionEndRequest,
) (*riskpb.PDESessionEndResponse, error) {

	if req == nil {
		return nil, status.Error(codes.InvalidArgument, "request is nil")
	}

	sess, ok := s.registry.End(req.SessionId, float64(req.AvgRiskScore), req.WasFlagged)
	if !ok {
		// Session may have already expired — not fatal
		s.log.Warn("EndSession: session not found in registry",
			zap.String("session", req.SessionId))
		return &riskpb.PDESessionEndResponse{
			Accepted: false,
			Reason:   "session not found (may have expired)",
		}, nil
	}

	s.db.RecordSessionEnd(sess)

	// Advance user phase based on cumulative session count
	newPhase := types.PhaseObservation
	if user, ok := s.engine.GetStore().GetUser(req.UserId); ok {
		user.SessionCount++
		user.Phase      = types.PhaseFor(user.SessionCount)
		user.LastSeenAt = time.Now()
		newPhase        = user.Phase
		s.engine.GetStore().UpsertUser(user)
		s.db.UpsertUser(user)
		s.log.Info("User phase updated after session",
			zap.String("user", req.UserId),
			zap.String("phase", user.Phase),
			zap.Int("sessions", user.SessionCount),
		)
	}

	return &riskpb.PDESessionEndResponse{
		Accepted: true,
		NewPhase: newPhase,
		Reason:   "session ended cleanly",
	}, nil
}

// ─────────────────────────────────────────────
//  SyncPolicy
// ─────────────────────────────────────────────

func (s *PDEServicer) SyncPolicy(
	ctx context.Context,
	req *riskpb.PolicySyncRequest,
) (*riskpb.PolicySyncResponse, error) {

	group := types.PolicyGroupDefault

	if req != nil && req.UserId != "" {
		if user, ok := s.engine.GetStore().GetUser(req.UserId); ok && user.PolicyID != "" {
			if g, ok := s.engine.GetStore().GetGroup(user.PolicyID); ok {
				group = g
			}
		}
	}

	syncIntervalS := int64(s.cfg.Policy.SyncInterval.Seconds())

	return &riskpb.PolicySyncResponse{
		PolicyGroupId:   group.ID,
		PolicyGroupName: group.Name,
		LowMax:          float32(group.LowMax),
		ElevatedMax:     float32(group.ElevatedMax),
		HighMax:         float32(group.HighMax),
		SoftDivisor:     float32(group.SoftDivisor),
		SyncIntervalS:   syncIntervalS,
		IssuedAt:        time.Now().Unix(),
	}, nil
}

// ─────────────────────────────────────────────
//  HealthCheck
// ─────────────────────────────────────────────

func (s *PDEServicer) HealthCheck(
	ctx context.Context,
	_ *riskpb.HealthRequest,
) (*riskpb.PDEHealthResponse, error) {

	return &riskpb.PDEHealthResponse{
		Healthy:        true,
		ActiveSessions: int32(s.registry.ActiveCount()),
		UptimeS:        float32(time.Since(startTime).Seconds()),
	}, nil
}

